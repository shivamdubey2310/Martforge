-- phase 6 

USE ROLE ACCOUNTADMIN;

-- 1. Warehouse compute consumption for MartForge workloads
SELECT 
    WAREHOUSE_NAME,
    SUM(CREDITS_USED) AS TOTAL_CREDITS_CONSUMED,
    MIN(START_TIME) AS FIRST_RUN,
    MAX(END_TIME) AS LATEST_RUN
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE WAREHOUSE_NAME = 'MARTFORGE_WH'
GROUP BY 1;

-- 2. Query execution metrics on MartForge transformations
SELECT 
    QUERY_TEXT,
    EXECUTION_TIME / 1000.0 AS EXECUTION_SECONDS,
    BYTES_SCANNED / (1024 * 1024) AS MB_SCANNED,
    CREDITS_USED_CLOUD_SERVICES,
    START_TIME
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE WAREHOUSE_NAME = 'MARTFORGE_WH'
  AND EXECUTION_STATUS = 'SUCCESS'
ORDER BY START_TIME DESC
LIMIT 10;