-- Phase 1.1
-- 1. Create dedicated role and user
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS MARTFORGE_ROLE;
GRANT ROLE MARTFORGE_ROLE TO ROLE SYSADMIN;

CREATE USER IF NOT EXISTS MARTFORGE_USER
    PASSWORD = 'MartForgePassword123!'
    DEFAULT_ROLE = MARTFORGE_ROLE
    DEFAULT_WAREHOUSE = MARTFORGE_WH
    MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE MARTFORGE_ROLE TO USER MARTFORGE_USER;

-- 2. Create an X-Small Warehouse with strict credit conservation
CREATE WAREHOUSE IF NOT EXISTS MARTFORGE_WH
    WITH 
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Dedicated warehouse for MartForge ELT workloads';

GRANT USAGE, OPERATE ON WAREHOUSE MARTFORGE_WH TO ROLE MARTFORGE_ROLE;

-- 3. Create RAW (landing) and ANALYTICS (transformations) databases
CREATE DATABASE IF NOT EXISTS MARTFORGE_RAW;
CREATE DATABASE IF NOT EXISTS MARTFORGE_ANALYTICS;

-- 4. Grant access privileges on RAW (Read-only for dbt, read-write for EL)
GRANT USAGE ON DATABASE MARTFORGE_RAW TO ROLE MARTFORGE_ROLE;
GRANT USAGE, CREATE SCHEMA ON DATABASE MARTFORGE_RAW TO ROLE MARTFORGE_ROLE;
GRANT SELECT ON ALL TABLES IN DATABASE MARTFORGE_RAW TO ROLE MARTFORGE_ROLE;
GRANT SELECT ON FUTURE TABLES IN DATABASE MARTFORGE_RAW TO ROLE MARTFORGE_ROLE;

-- 5. Grant access privileges on ANALYTICS (Full transformation control)
GRANT USAGE, CREATE SCHEMA ON DATABASE MARTFORGE_ANALYTICS TO ROLE MARTFORGE_ROLE;
GRANT ALL PRIVILEGES ON DATABASE MARTFORGE_ANALYTICS TO ROLE MARTFORGE_ROLE;


